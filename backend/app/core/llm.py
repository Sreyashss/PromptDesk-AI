"""
Google GenAI Client Wrapper using official google-genai SDK
Supports live Gemini 3.7 Flash execution with intelligent error handling.
"""

import time
import json
import logging
from typing import Optional, Dict, Any
from app.config import GEMINI_API_KEY, GEMINI_MODEL, GEMINI_MAX_OUTPUT_TOKENS

logger = logging.getLogger("promptdesk.llm")

# Initialize client if API key is present
_client = None

def get_genai_client():
    global _client
    if _client is not None:
        return _client
    
    if not GEMINI_API_KEY:
        logger.warning("GEMINI_API_KEY not configured. Live LLM calls will fail or fall back to test mode.")
        return None
        
    try:
        from google import genai
        _client = genai.Client(api_key=GEMINI_API_KEY)
        return _client
    except Exception as e:
        logger.error(f"Failed to initialize google-genai client: {e}")
        return None

# User-friendly safe messages for API failures
API_ERROR_FRIENDLY_MESSAGES = {
    "429_RESOURCE_EXHAUSTED": "Gemini API quota exhausted. Please try again after the quota resets.",
    "503_UNAVAILABLE": "Gemini API is currently experiencing high demand. Please try again in a few moments.",
    "TIMEOUT": "Gemini API request timed out. Please try again.",
    "CONNECTION_ERROR": "Unable to connect to the Gemini API. Please check your network connection.",
    "API_ERROR": "An error occurred while communicating with the Gemini API. Please try again.",
    "NO_CANDIDATES": "No response generated by Gemini API. Please try again."
}

def is_api_error_text(text: Optional[str]) -> bool:
    """Checks whether the text represents an API error message (either legacy or user-friendly)."""
    if not text:
        return True
    if text.startswith("[API_ERROR:") or text.startswith("NOT_EVALUATED:") or text.startswith("[BLOCKED/INCOMPLETE:"):
        return True
    return any(text.startswith(msg) or msg in text for msg in API_ERROR_FRIENDLY_MESSAGES.values())

def generate_llm_response(
    system_instruction: str,
    user_query: str,
    temperature: float = 0.2,
    model: Optional[str] = None
) -> Dict[str, Any]:
    """
    Generates a response from Gemini using official google-genai SDK.
    Returns dictionary with text, latency_ms, and metadata.
    """
    selected_model = model or GEMINI_MODEL
    client = get_genai_client()
    
    start_time = time.time()
    
    if client is None:
        # Fallback simulation for offline testing if no key is configured yet
        return _mock_llm_response(system_instruction, user_query, start_time)
        
    retries = 2
    for attempt in range(retries + 1):
        try:
            from google.genai import types
            
            response = client.models.generate_content(
                model=selected_model,
                contents=user_query,
                config=types.GenerateContentConfig(
                    system_instruction=system_instruction,
                    temperature=temperature,
                    max_output_tokens=GEMINI_MAX_OUTPUT_TOKENS
                )
            )
            latency_ms = int((time.time() - start_time) * 1000)

            # Inspect candidates and finish reason
            candidate = response.candidates[0] if (response.candidates and len(response.candidates) > 0) else None
            if candidate is None:
                logger.warning(f"Gemini API returned no candidates for model '{selected_model}'.")
                return {
                    "text": API_ERROR_FRIENDLY_MESSAGES["NO_CANDIDATES"],
                    "latency_ms": latency_ms,
                    "model": selected_model,
                    "success": False,
                    "error": "No candidates returned by Gemini API",
                    "error_type": "NO_CANDIDATES",
                    "finish_reason": "NO_CANDIDATES",
                    "truncated": False
                }

            finish_reason = getattr(candidate, "finish_reason", None)
            finish_reason_str = (
                finish_reason.name if hasattr(finish_reason, "name")
                else (finish_reason.value if hasattr(finish_reason, "value") else str(finish_reason))
            )
            text_content = response.text if response.text else ""

            # Check for truncation due to output token limit
            if finish_reason_str == "MAX_TOKENS":
                logger.warning(
                    f"Gemini response truncated: model='{selected_model}', finish_reason={finish_reason_str}, "
                    f"max_output_tokens={GEMINI_MAX_OUTPUT_TOKENS}. Output limit reached mid-generation."
                )
                return {
                    "text": text_content.strip(),
                    "latency_ms": latency_ms,
                    "model": selected_model,
                    "success": False,
                    "error": f"Response truncated: maximum output tokens limit reached (finish_reason: {finish_reason_str})",
                    "error_type": "MAX_TOKENS_TRUNCATED",
                    "finish_reason": finish_reason_str,
                    "truncated": True
                }

            # Check for safety or other abnormal termination
            if finish_reason_str not in ("STOP", None):
                logger.warning(
                    f"Gemini response ended abnormally: model='{selected_model}', finish_reason={finish_reason_str}."
                )
                return {
                    "text": text_content.strip() or f"[BLOCKED/INCOMPLETE: finish_reason={finish_reason_str}]",
                    "latency_ms": latency_ms,
                    "model": selected_model,
                    "success": False,
                    "error": f"Response generation incomplete (finish_reason: {finish_reason_str})",
                    "error_type": finish_reason_str,
                    "finish_reason": finish_reason_str,
                    "truncated": False
                }

            logger.info(
                f"Gemini response generated successfully: model='{selected_model}', "
                f"finish_reason={finish_reason_str}, latency={latency_ms}ms"
            )
            return {
                "text": text_content.strip(),
                "latency_ms": latency_ms,
                "model": selected_model,
                "success": True,
                "error": None,
                "finish_reason": finish_reason_str,
                "truncated": False
            }
        except Exception as e:
            err_str = str(e)
            if ("503" in err_str or "UNAVAILABLE" in err_str) and attempt < retries:
                logger.warning(f"Transient Gemini API 503 on attempt {attempt + 1}, retrying in 2s: {err_str}")
                time.sleep(2)
                continue

            logger.error(f"Gemini API invocation error: {err_str}")
            latency_ms = int((time.time() - start_time) * 1000)
            
            # Categorize error type and assign safe user-friendly message
            if "429" in err_str or "RESOURCE_EXHAUSTED" in err_str or "quota" in err_str.lower():
                err_type = "429_RESOURCE_EXHAUSTED"
                user_msg = API_ERROR_FRIENDLY_MESSAGES["429_RESOURCE_EXHAUSTED"]
            elif "503" in err_str or "UNAVAILABLE" in err_str:
                err_type = "503_UNAVAILABLE"
                user_msg = API_ERROR_FRIENDLY_MESSAGES["503_UNAVAILABLE"]
            elif "timeout" in err_str.lower() or "deadline" in err_str.lower():
                err_type = "TIMEOUT"
                user_msg = API_ERROR_FRIENDLY_MESSAGES["TIMEOUT"]
            elif "connection" in err_str.lower():
                err_type = "CONNECTION_ERROR"
                user_msg = API_ERROR_FRIENDLY_MESSAGES["CONNECTION_ERROR"]
            else:
                err_type = "API_ERROR"
                user_msg = API_ERROR_FRIENDLY_MESSAGES["API_ERROR"]
                
            return {
                "text": user_msg,
                "latency_ms": latency_ms,
                "model": selected_model,
                "success": False,
                "error": err_str,
                "error_type": err_type,
                "finish_reason": err_type,
                "truncated": False
            }

def evaluate_with_judge_llm(judge_prompt: str, user_query: str, model_response: str) -> Dict[str, Any]:
    """
    Uses Gemini as a Judge to score model output according to the structured rubric.
    Guarantees that API error messages are never passed to the judge.
    """
    if not model_response or is_api_error_text(model_response):
        return {
            "success": False,
            "error": "Cannot evaluate an API error response",
            "evaluation_reasoning": "Response generation failed due to API error."
        }

    client = get_genai_client()
    if client is None:
        return _mock_judge_score(user_query, model_response)
        
    try:
        from google.genai import types
        
        prompt_content = f"""
Customer Query:
"{user_query}"

Assistant Response to Evaluate:
"{model_response}"

Evaluate the response now based on the rubric and return ONLY valid JSON.
"""
        response = client.models.generate_content(
            model=GEMINI_MODEL,
            contents=prompt_content,
            config=types.GenerateContentConfig(
                system_instruction=judge_prompt,
                temperature=0.1,
                response_mime_type="application/json"
            )
        )
        raw_text = response.text.strip() if response.text else "{}"
        parsed_json = json.loads(raw_text)
        parsed_json["success"] = True
        return parsed_json
    except Exception as e:
        err_str = str(e)
        logger.error(f"Judge evaluation failed: {err_str}")
        return {
            "success": False,
            "error": err_str,
            "evaluation_reasoning": f"Judge evaluation failed due to API error: {err_str}"
        }

